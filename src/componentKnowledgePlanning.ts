/** 子会话只继承只读知识能力，不继承宿主动作或知识写入工具。 */
export function childKnowledgeTools(tools: unknown[] = []): unknown[] {
  return tools.filter(tool => !!tool && typeof tool === "object"
    && "name" in tool && tool.name === "knowledge");
}
